#!/usr/bin/env node
// Guards the URLs that shipped apps and the company registry depend on.
//
//   node scripts/check-legacy.mjs dist                 check a local build
//   node scripts/check-legacy.mjs https://example.com  check a deployed site
//   node scripts/check-legacy.mjs --write              re-record fingerprints (only after an intended change)
//
// Every file in public/ is frozen: it must be served byte-for-byte as recorded.
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile, stat } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const manifestPath = join(root, 'scripts', 'legacy-manifest.json');

// URLs as the apps and old links use them. Each must answer 200 on a deployed site.
const urlForms = [
  '/',
  '/corporate.html',
  '/corporate/',
  '/calendar/',
  '/calendar/index.html',
  '/calendar/privacy/index.html',
  '/calendar/terms/index.html',
  '/greatparent/privacy',
  '/greatparent/privacy/',
  '/greatparent/terms',
  '/greatparent/terms/',
  '/baby-activity-planner/privacy',
  '/baby-activity-planner/terms',
  '/can-we-meet/',
  '/can-we-meet/index.html',
  '/timezone-tangle/',
  '/active-reps/',
];

// Pages generated by Astro that must exist in the build.
const generated = ['index.html', 'corporate/index.html'];

// Files in public/ that belong to the new site, not the legacy one. Not frozen.
const notFrozen = new Set([
  'favicon.svg',
  'favicon.ico',
  'apple-touch-icon.png',
  'og.png',
  'robots.txt',
]);

const sha = (buf) => createHash('sha256').update(buf).digest('hex');

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (entry.name === '.DS_Store') continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else out.push(full);
  }
  return out;
}

async function writeManifest() {
  const pub = join(root, 'public');
  const files = {};
  for (const f of (await walk(pub)).sort()) {
    const rel = relative(pub, f).split(sep).join('/');
    if (!notFrozen.has(rel)) files[rel] = sha(await readFile(f));
  }
  await writeFile(manifestPath, JSON.stringify(files, null, 2) + '\n');
  console.log(`Recorded ${Object.keys(files).length} frozen files.`);
}

async function checkDir(dir, manifest) {
  let failed = 0;
  for (const [path, hash] of Object.entries(manifest)) {
    try {
      const got = sha(await readFile(join(dir, path)));
      if (got !== hash) { failed++; console.log(`CHANGED  ${path}`); }
    } catch { failed++; console.log(`MISSING  ${path}`); }
  }
  for (const path of generated) {
    try { await stat(join(dir, path)); } catch { failed++; console.log(`MISSING  ${path} (generated page)`); }
  }
  return failed;
}

async function checkSite(base, manifest) {
  let failed = 0;
  const encode = (p) => p.split('/').map(encodeURIComponent).join('/');
  for (const [path, hash] of Object.entries(manifest)) {
    const res = await fetch(`${base}/${encode(path)}`);
    const body = Buffer.from(await res.arrayBuffer());
    if (res.status !== 200) { failed++; console.log(`${res.status}      ${path}`); }
    else if (sha(body) !== hash) { failed++; console.log(`CHANGED  ${path}`); }
  }
  for (const path of urlForms) {
    const res = await fetch(base + path);
    if (res.status !== 200) { failed++; console.log(`${res.status}      ${path}`); }
  }
  return failed;
}

const target = process.argv[2];
if (target === '--write') {
  await writeManifest();
} else if (!target) {
  console.error('Usage: check-legacy.mjs <dist-dir | https://site> | --write');
  process.exit(2);
} else {
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  const failed = target.startsWith('http')
    ? await checkSite(target.replace(/\/$/, ''), manifest)
    : await checkDir(join(root, target), manifest);
  const total = Object.keys(manifest).length;
  if (failed) { console.log(`\n${failed} problem(s).`); process.exit(1); }
  console.log(`OK: ${total} frozen files intact${target.startsWith('http') ? `, ${urlForms.length} URLs answer 200` : ''}.`);
}
